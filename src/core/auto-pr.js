import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { generateFix, applyFix } from "./autofix.js";

export function createFixBranch({ repoRoot = ".", branchName = null }) {
  const timestamp = new Date().toISOString().slice(0, 10).replace(/-/g, "");
  const name = branchName || `codeguardian/fix-${timestamp}`;

  try {
    execFileSync("git", ["checkout", "-b", name], { cwd: repoRoot, encoding: "utf8", timeout: 10_000 });
    return name;
  } catch {
    return null;
  }
}

export function commitFixes({ repoRoot = ".", fixes = [] }) {
  if (fixes.length === 0) return false;

  const packageFiles = new Set();
  for (const fix of fixes) {
    if (fix.file) packageFiles.add(fix.file);
  }

  for (const file of packageFiles) {
    try {
      execFileSync("git", ["add", "--", file], { cwd: repoRoot, encoding: "utf8", timeout: 5000 });
    } catch { /* skip */ }
  }

  const message = `CodeGuardian: fix ${fixes.length} dependency CVE(s)\n\n` +
    fixes.map((f) => `- ${f.packageName} ${f.from} → ${f.to}`).join("\n");

  try {
    execFileSync("git", ["commit", "-m", message], { cwd: repoRoot, encoding: "utf8", timeout: 10_000 });
    return true;
  } catch {
    return false;
  }
}

export function pushAndCreatePr({ repoRoot = ".", branch, title, body }) {
  try {
    execFileSync("git", ["push", "-u", "origin", branch], { cwd: repoRoot, encoding: "utf8", timeout: 30_000 });
  } catch {
    return { success: false, error: "push failed" };
  }

  try {
    const result = execFileSync(
      "gh",
      ["pr", "create", "--title", title, "--body", body, "--head", branch],
      { cwd: repoRoot, encoding: "utf8", timeout: 30_000 }
    );
    const urlMatch = result.match(/https:\/\/github\.com\/[^\s]+\/pull\/\d+/);
    return { success: true, url: urlMatch ? urlMatch[0] : null };
  } catch {
    return { success: false, error: "PR creation failed" };
  }
}

export function autoFixAndPr({ reportPath, repoRoot = ".", createPr = false }) {
  if (!fs.existsSync(reportPath)) {
    return { success: false, error: "Report not found" };
  }

  const report = JSON.parse(fs.readFileSync(reportPath, "utf8"));
  const allFixes = [];

  for (const repo of report.repositories) {
    for (const finding of repo.findings) {
      const fix = generateFix(finding, repo.path);
      if (fix && fix.safe) allFixes.push(fix);
    }
  }

  if (allFixes.length === 0) {
    return { success: true, fixes: 0, message: "No safe fixes available" };
  }

  const appliedFixes = [];
  for (const fix of allFixes) {
    const repo = report.repositories.find((r) =>
      r.findings.some((f) => f.id === fix.findingId)
    );
    if (repo && applyFix(fix, repo.path)) {
      appliedFixes.push(fix);
    }
  }

  if (appliedFixes.length === 0) {
    return { success: true, fixes: 0, message: "No fixes could be applied" };
  }

  if (!createPr) {
    return { success: true, fixes: appliedFixes.length, applied: appliedFixes };
  }

  const branch = createFixBranch({ repoRoot });
  if (!branch) {
    return { success: false, error: "Could not create branch" };
  }

  commitFixes({ repoRoot, fixes: appliedFixes });

  const title = `CodeGuardian: fix ${appliedFixes.length} dependency CVE(s)`;
  const body = [
    "## 🛡️ CodeGuardian Auto-Fix",
    "",
    `${appliedFixes.length} dependency vulnerability fix(es) applied:`,
    "",
    ...appliedFixes.map((f => `- **${f.packageName}**: ${f.from} → ${f.to}`)),
    "",
    "---",
    "*Generated by CodeGuardian Scanner*"
  ].join("\n");

  const prResult = pushAndCreatePr({ repoRoot, branch, title, body });
  return { success: prResult.success, fixes: appliedFixes.length, pr: prResult };
}
